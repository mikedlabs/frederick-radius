/**
 * DFP-scraped places (1,428 businesses) — wire as additional Place entries.
 * Slugs from DFP that collide with curated PLACES are dropped (curated wins).
 * Source: downtownfrederick.org/place/* scraped May 2026.
 */
const CURATED_SLUGS = new Set(PLACES.map((p) => p.slug));
const PLACES_DFP: Place[] = (PLACES_DFP_RAW as Array<{
  slug: string; name: string; category: string; subcategories?: string[];
  short_blurb: string; address: string; city: string; postal_code: string;
  municipality: string; geom: LngLat;
  website?: string; phone?: string; instagram?: string;
  price_band?: number; google_place_id?: string;
  feature_score: number; updated_at: string;
}>)
  .filter((p) => !CURATED_SLUGS.has(p.slug))
  .map((p) => ({
    slug: p.slug,
    name: p.name,
    category: p.category,
    subcategories: p.subcategories && p.subcategories.length > 0 ? p.subcategories : undefined,
    short_blurb: p.short_blurb,
    address: p.address,
    city: p.city,
    state: "MD" as const,
    postal_code: p.postal_code,
    municipality: p.municipality,
    geom: p.geom,
    website: p.website,
    phone: p.phone,
    instagram: p.instagram,
    price_band: p.price_band as 1 | 2 | 3 | 4 | undefined,
    google_place_id: p.google_place_id,
    is_verified: false,
    hours_verified: false,
    is_operational: "operational" as const,
    feature_score: p.feature_score,
    source: "dfp" as const,
    updated_at: p.updated_at,
  }));

// Re-export PLACES with DFP merged in.
PLACES.push(...PLACES_DFP);

export const PLACE_BY_SLUG = Object.fromEntries(
  PLACES.map((p) => [p.slug, p])
) as Record<string, Place>;

export function placesByCategory(slug: string): Place[] {
  return PLACES.filter(
    (p) => p.category === slug || (p.subcategories ?? []).includes(slug)
  );
}

export function placesByMunicipality(slug: string): Place[] {
  return PLACES.filter((p) => p.municipality === slug);
}
