#!/usr/bin/env node
/**
 * Upload large committed public assets to Vercel Blob and generate a path map.
 *
 * Safe by design:
 * - uploads only known static image roots
 * - writes src/data/blob-static-assets.generated.ts
 * - does NOT delete files from public/
 *
 * Run after pulling project env vars so BLOB_READ_WRITE_TOKEN is available:
 *   vercel env pull .env.local
 *   npm run blob:static-assets
 */
import { put } from "@vercel/blob";
import { createHash } from "node:crypto";
import { promises as fs } from "node:fs";
import path from "node:path";

const ROOTS = ["public/from-above", "public/history-photos", "public/images/seasons"];
const OUT = "src/data/blob-static-assets.generated.ts";
const TOKEN = process.env.BLOB_READ_WRITE_TOKEN;
const EXTENSIONS = new Set([".avif", ".gif", ".jpeg", ".jpg", ".png", ".webp"]);

if (!TOKEN) {
  console.error("BLOB_READ_WRITE_TOKEN is not set. Run `vercel env pull .env.local` first.");
  process.exit(1);
}

async function walk(dir) {
  const out = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await walk(full));
    else if (EXTENSIONS.has(path.extname(entry.name).toLowerCase())) out.push(full);
  }
  return out;
}

function publicPath(file) {
  return "/" + path.relative("public", file).split(path.sep).join("/");
}

function contentType(file) {
  const ext = path.extname(file).toLowerCase();
  if (ext === ".avif") return "image/avif";
  if (ext === ".gif") return "image/gif";
  if (ext === ".png") return "image/png";
  if (ext === ".webp") return "image/webp";
  return "image/jpeg";
}

function blobPath(file, bytes) {
  const rel = path.relative("public", file).split(path.sep).join("/");
  const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
  const parsed = path.parse(rel);
  return `static/${parsed.dir}/${parsed.name}-${hash}${parsed.ext}`.replace(/\/+/g, "/");
}

const files = (await Promise.all(ROOTS.map(walk))).flat().sort();
const map = {};
for (const file of files) {
  const bytes = await fs.readFile(file);
  const pathname = blobPath(file, bytes);
  const blob = await put(pathname, bytes, {
    access: "public",
    token: TOKEN,
    contentType: contentType(file),
    allowOverwrite: true,
  });
  map[publicPath(file)] = blob.url;
  console.log(`${publicPath(file)} -> ${blob.url}`);
}

const body = `/**\n * Generated by \`npm run blob:static-assets\`.\n *\n * Maps committed public asset paths to their Vercel Blob URLs.\n */\nexport const BLOB_STATIC_ASSETS: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;
await fs.writeFile(OUT, body);
console.log(`\nWrote ${OUT} with ${Object.keys(map).length} assets.`);
